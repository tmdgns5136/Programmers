WITH RANKED_ECOLI AS(
    SELECT ID, PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) AS PERC
    FROM ECOLI_DATA
)
SELECT ID, CASE
                WHEN PERC <= 0.25 THEN 'CRITICAL'
                WHEN PERC <= 0.50 THEN 'HIGH'
                WHEN PERC <= 0.75 THEN 'MEDIUM'
                ELSE 'LOW'
            END AS COLONY_NAME
FROM RANKED_ECOLI
ORDER BY ID ASC;